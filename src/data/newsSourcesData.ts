import { NewsSourceProfile, MonthlyCredibilityPoint } from '../types';

const MONTHS = [
  "Nov '25", "Dec '25", "Jan '26", "Feb '26", "Mar '26", "Apr '26",
  "May '26", "Jun '26", "Jul '26", "Aug '26", "Sep '26", "Oct '26"
];

function generateTrend(baseScore: number, variance: number, trendSlope: number, multiplierBase: number): MonthlyCredibilityPoint[] {
  return MONTHS.map((month, idx) => {
    const noise = Math.sin(idx * 0.9) * variance;
    const score = Math.max(0.08, Math.min(0.99, Number((baseScore + idx * trendSlope + noise).toFixed(3))));
    const corroborated = Math.max(0, Math.round(score * 18 + noise * 5));
    const retractions = score > 0.85 ? (idx % 4 === 0 ? 1 : 0) : (score < 0.40 ? Math.round(3 + Math.abs(noise * 4)) : (idx % 2 === 0 ? 1 : 0));
    const exposure = Number((multiplierBase * (score / 0.85)).toFixed(2));

    return {
      month,
      score,
      corroboratedArticles: corroborated,
      retractionsOrCorrections: retractions,
      exposureMultiplier: exposure,
    };
  });
}

